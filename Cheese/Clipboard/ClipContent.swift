import CryptoKit
import Foundation

enum ClipKind: String, Codable, Sendable {
    case text
    case richText
    case image
    case files
}

/// One type/data pair of a pasteboard item, kept verbatim so items paste back exactly as copied.
struct PasteboardRepresentation: Codable, Equatable, Sendable {
    var type: String
    var data: Data
}

/// Every representation of one pasteboard item.
struct PasteboardItemContent: Codable, Equatable, Sendable {
    var representations: [PasteboardRepresentation]

    func data(forType type: String) -> Data? {
        representations.first { $0.type == type }?.data
    }
}

/// What the monitor read off the pasteboard, before it's stored.
enum CapturedClip: Equatable, Sendable {
    case text(plain: String, items: [PasteboardItemContent], isRich: Bool)
    case image(data: Data)
    case files([URL])
}

/// Pasteboard type identifiers Cheese cares about.
enum PasteboardTypeID {
    static let concealed = "org.nspasteboard.ConcealedType"
    static let transient = "org.nspasteboard.TransientType"
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    static let plainText = "public.utf8-plain-text"
    static let rtf = "public.rtf"
    static let rtfd = "com.apple.flat-rtfd"
    static let html = "public.html"
    static let fileURL = "public.file-url"
    static let png = "public.png"
    static let tiff = "public.tiff"
    static let jpeg = "public.jpeg"
    static let heic = "public.heic"

    /// Markers password managers and similar apps put on secrets and throwaway data.
    static let privacyMarkers: Set<String> = [concealed, transient, autoGenerated]
    /// Image types Cheese reads, best first.
    static let imageTypes = [png, tiff, jpeg, heic]
    static let richTextTypes: Set<String> = [rtf, rtfd, html]
}

/// Decides what kind of clip a pasteboard holds from its types alone, without reading any data.
enum ClipClassifier {
    /// - Parameter itemTypes: the types of each pasteboard item, in order.
    /// - Returns: nil when the pasteboard is empty, carries a privacy marker, or holds nothing Cheese records.
    static func classify(_ itemTypes: [[String]]) -> ClipKind? {
        let all = Set(itemTypes.joined())
        guard !all.isEmpty, all.isDisjoint(with: PasteboardTypeID.privacyMarkers) else { return nil }

        // Finder puts file names and icons alongside file URLs, so files win.
        if all.contains(PasteboardTypeID.fileURL) { return .files }

        let hasRichText = !all.isDisjoint(with: PasteboardTypeID.richTextTypes)
        // Word processors add a picture of the text; real text wins over images.
        let hasText = all.contains(PasteboardTypeID.plainText)
            || all.contains(PasteboardTypeID.rtf)
            || all.contains(PasteboardTypeID.rtfd)
        if hasText { return hasRichText ? .richText : .text }

        // Browsers' "Copy Image" can add HTML markup but no text; treat that as an image.
        if PasteboardTypeID.imageTypes.contains(where: all.contains) { return .image }
        if all.contains(PasteboardTypeID.html) { return .richText }
        return nil
    }
}

/// Content fingerprints used to spot re-copies of an item already in history.
enum ClipHasher {
    static func hash(text: String) -> String {
        "text:" + digest(Data(text.utf8))
    }

    static func hash(imageData: Data) -> String {
        "image:" + digest(imageData)
    }

    static func hash(files: [URL]) -> String {
        "files:" + digest(Data(files.map { $0.standardizedFileURL.path(percentEncoded: false) }.joined(separator: "\n").utf8))
    }

    private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
