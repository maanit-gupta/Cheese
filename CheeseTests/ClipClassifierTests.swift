import Foundation
import Testing
@testable import Cheese

struct ClipClassifierTests {
    private typealias T = PasteboardTypeID

    @Test func emptyPasteboardIsIgnored() {
        #expect(ClipClassifier.classify([]) == nil)
        #expect(ClipClassifier.classify([[]]) == nil)
    }

    @Test(arguments: [T.concealed, T.transient, T.autoGenerated])
    func privacyMarkersAreSkipped(_ marker: String) {
        #expect(ClipClassifier.classify([[T.plainText, marker]]) == nil)
        // A marker on any item skips the whole copy.
        #expect(ClipClassifier.classify([[T.plainText], [marker]]) == nil)
    }

    @Test func plainText() {
        #expect(ClipClassifier.classify([[T.plainText]]) == .text)
    }

    @Test func richText() {
        #expect(ClipClassifier.classify([[T.plainText, T.rtf]]) == .richText)
        #expect(ClipClassifier.classify([[T.plainText, T.html]]) == .richText)
        #expect(ClipClassifier.classify([[T.rtfd]]) == .richText)
    }

    @Test func textWinsOverPictureOfText() {
        #expect(ClipClassifier.classify([[T.plainText, T.rtf, T.tiff, T.png]]) == .richText)
    }

    @Test func filesWinOverNamesAndIcons() {
        #expect(ClipClassifier.classify([[T.fileURL, T.plainText, T.tiff]]) == .files)
    }

    @Test func images() {
        #expect(ClipClassifier.classify([[T.tiff]]) == .image)
        #expect(ClipClassifier.classify([[T.png, T.tiff]]) == .image)
        #expect(ClipClassifier.classify([[T.jpeg]]) == .image)
        // Browsers' Copy Image adds markup but no text.
        #expect(ClipClassifier.classify([[T.tiff, T.html]]) == .image)
    }

    @Test func htmlAloneIsRichText() {
        #expect(ClipClassifier.classify([[T.html]]) == .richText)
    }

    @Test func unknownTypesAreIgnored() {
        #expect(ClipClassifier.classify([["com.example.private"]]) == nil)
    }
}

struct ClipHasherTests {
    @Test func sameContentSameHash() {
        #expect(ClipHasher.hash(text: "hello") == ClipHasher.hash(text: "hello"))
        #expect(ClipHasher.hash(text: "hello") != ClipHasher.hash(text: "hello "))
    }

    @Test func kindsDontCollide() {
        let data = Data("hello".utf8)
        #expect(ClipHasher.hash(text: "hello") != ClipHasher.hash(imageData: data))
    }

    @Test func filesHashByStandardizedPath() {
        let a = [URL(filePath: "/tmp/a/../b.txt")]
        let b = [URL(filePath: "/tmp/b.txt")]
        #expect(ClipHasher.hash(files: a) == ClipHasher.hash(files: b))
        #expect(ClipHasher.hash(files: b) != ClipHasher.hash(files: b + b))
    }
}

struct RetentionPolicyTests {
    private func candidate(_ age: TimeInterval, pinned: Bool = false) -> RetentionCandidate {
        RetentionCandidate(id: UUID(), isPinned: pinned, lastCopiedAt: Date(timeIntervalSince1970: 1_000_000 - age))
    }

    @Test func keepsNewestUnpinned() {
        let items = (0..<5).map { candidate(TimeInterval($0)) }
        let removed = RetentionPolicy.itemsToRemove(from: items.shuffled(), limit: 3)
        #expect(Set(removed) == Set([items[3].id, items[4].id]))
    }

    @Test func pinnedDontCountAndAreNeverRemoved() {
        let pinned = (0..<10).map { candidate(TimeInterval(100 + $0), pinned: true) }
        let unpinned = (0..<3).map { candidate(TimeInterval($0)) }
        #expect(RetentionPolicy.itemsToRemove(from: pinned + unpinned, limit: 3).isEmpty)
        #expect(RetentionPolicy.itemsToRemove(from: pinned + unpinned, limit: 2) == [unpinned[2].id])
    }

    @Test func underLimitRemovesNothing() {
        #expect(RetentionPolicy.itemsToRemove(from: [candidate(1)], limit: 200).isEmpty)
        #expect(RetentionPolicy.itemsToRemove(from: [], limit: 0).isEmpty)
    }

    @Test func zeroLimitRemovesAllUnpinned() {
        let items = [candidate(1), candidate(2, pinned: true)]
        #expect(RetentionPolicy.itemsToRemove(from: items, limit: 0) == [items[0].id])
    }
}
